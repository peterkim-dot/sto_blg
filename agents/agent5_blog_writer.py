"""에이전트 5: 블로그 글 통합 작성"""
from utils.llm_client import call_llm

SYSTEM_PROMPT = """당신은 주식/투자 분야 전문 블로그 작가입니다.

역할:
- 4개 에이전트의 분석 결과를 하나의 매력적인 블로그 글로 통합
- 독자가 처음부터 끝까지 읽고 싶은 흐름 구성
- SEO 친화적인 제목과 구조
- 복사-붙여넣기만으로 블로그에 바로 게시 가능한 완성도

작성 원칙:
- 도입부: 오늘 시장의 핵심을 한 줄로 요약 (독자 주목)
- 본문: 큰 그림(매크로) → 개별 종목 → 기술적 분석 → 전망 순서
- 마무리: 핵심 포인트 정리 + 내일 주목할 포인트
- 자연스러운 문단 연결 (기계적 나열 X)
- 이모지를 적절히 활용하여 가독성 향상
- 면책조항 포함

블로그 글 구조:
1. 🔥 제목 (클릭을 유도하는 매력적인 제목)
2. 📌 한줄 요약 (TL;DR)
3. 📊 시장 개요 & 매크로 분석 (에이전트1 기반)
4. 🚀 오늘의 급등/급락주 분석 (에이전트2 기반)
5. 📈 차트로 보는 기술적 분석 (에이전트3 기반)
6. 🔮 종합 전망 & 매매 전략 (에이전트4 기반)
7. 📝 내일 주목할 포인트
8. ⚠️ 면책조항

마크다운 형식으로 작성하되, 블로그 플랫폼(네이버, 티스토리 등)에서 바로 사용 가능하도록 깔끔하게 포맷팅해주세요."""


def run(agent1_result, agent2_result, agent3_result, agent4_result, session_type="morning"):
    """블로그 글 통합 작성 에이전트 실행"""
    time_label = "아침 브리핑" if session_type == "morning" else "마감 리뷰"

    user_prompt = f"""아래 4개 에이전트의 분석 결과를 하나의 완성된 블로그 글로 통합해주세요.
글의 유형: [{time_label}]

=== 에이전트1: 시장 & 외부 요인 분석 ===
{agent1_result}

=== 에이전트2: 급등/급락주 분석 ===
{agent2_result}

=== 에이전트3: 차트 기술적 분석 ===
{agent3_result}

=== 에이전트4: 종합 전망 & 매매 전략 ===
{agent4_result}

요구사항:
1. 위 4개 분석을 자연스럽게 하나의 글로 통합
2. 독자의 흐름을 고려한 구성 (매크로 → 종목 → 차트 → 전망)
3. 핵심 내용이 돋보이도록 포맷팅
4. 블로그에 복사-붙여넣기만 하면 되는 완성도
5. "{time_label}" 느낌에 맞는 톤
6. SEO를 고려한 제목 작성
7. 면책조항 반드시 포함"""

    result = call_llm(SYSTEM_PROMPT, user_prompt, max_tokens=8000)
    return result


if __name__ == "__main__":
    print("에이전트 5는 에이전트 1~4의 결과가 필요합니다.")
